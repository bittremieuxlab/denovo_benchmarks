"""
Script to convert predictions from the algorithm output format 
to the common output format.
"""

import argparse
import os
import re
import numpy as np
import pandas as pd
from tqdm import tqdm
from pyteomics import mgf
from algorithms.base import OutputMapperBase


class OutputMapper(OutputMapperBase):
    REPLACEMENTS = [
        # Amino acid modifications.
        ("(+57.02)", "[UNIMOD:4]"),    # Carbamidomethylation
        ("(+4.03)", "[UNIMOD:481]"),    # SILAC K (Medium) 
        ("(+6.02)", "[UNIMOD:188]"),    # SILAC R (Medium) 
        ("(+8.01)", "[UNIMOD:259]"),    # SILAC K (Heavy)
        ("(+10.01)", "[UNIMOD:267]"),    # SILAC R (Heavy) 
        ("(+229.16)", "[UNIMOD:737]"),    # TMT
        ("(-17.03)", "[UNIMOD:385]"),    # Loss of ammonia
        ("(+0.98)", "[UNIMOD:7]"),     # Deamidation
        ("(+14.02)", "[UNIMOD:34]"),    # Methylation
        ("(+15.99)", "[UNIMOD:35]"),    # Oxidation
        ("(+21.98)", "[UNIMOD:30]"),    # Sodium adduct
        ("(+26.02)", "[UNIMOD:254]"),    # Acetaldehyde +26
        ("(+27.99)", "[UNIMOD:122]"),    # Formylation
        ("(+28.03)", "[UNIMOD:36]"),    # di-Methylation
        ("(+42.01)", "[UNIMOD:1]"),    # Acetylation
        ("(+42.05)", "[UNIMOD:37]"),    # tri-Methylation
        ("(+44.99)", "[UNIMOD:354]"),   # Oxidation to nitro
        ("(+53.92)", "[UNIMOD:952]"),    # Iron(II) adducts
        ("(+55.92)", "[UNIMOD:953]"),   # Replacement of 2 protons by nickel
        ("(+56.03)", "[UNIMOD:58]"),    # Propionyl
        ("(+68.03)", "[UNIMOD:1363]"),    # Crotonylation
        ("(+70.04)", "[UNIMOD:1289]"),    # Butyryl
        ("(+79.97)", "[UNIMOD:21]"),   # Phospho
        ("(+86.00)", "[UNIMOD:747]"),    # Malonylation
        ("(+86.04)", "[UNIMOD:1849]"),   # hydroxyisobutyrylation 
        ("(+100.02)", "[UNIMOD:64]"),    # Succinyl
        ("(+114.03)", "[UNIMOD:1848]"),    # Gluratylation
        ("(+114.04)", "[UNIMOD:121]"),    # ubiquitinylation
        ("(+226.08)", "[UNIMOD:3]"),    # Biotinylation
    ]
    PEP_SPLIT_PATTERN = r"(?<=.)(?=[A-Z])"
    # MOD_PATTERN = r"\[UNIMOD:[0-9]+\]"
    SCORE_SCALE_CONST = 100

    def __init__(self, input_dir: str) -> None:
        """TODO."""
        fnames = [fname for fname in os.listdir(input_dir) if fname.endswith(".mgf")]
        self.file_names = [fname.split(".")[0] for fname in sorted(fnames)]

        self.file_scan2spec_idx = {}
        for fname in self.file_names:
            print(fname, ": get spectrum indices.")
            filename = fname + ".mgf"
            file_path = os.path.join(input_dir, filename)
            
            spectra = mgf.read(file_path)
            for i in tqdm(range(len(spectra))):
                # PEAKS scan id = MGF's "scans" field if available, otherwise 1-based spectrum index
                params = spectra[i]["params"]
                scan = params.get("scans", i + 1)
                file_scan = f"{filename}:{scan}"
                spec_idx = f"{fname}:{i}"
                self.file_scan2spec_idx[file_scan] = spec_idx
            spectra.close()
        return

    def _parse_scores(self, scores: str) -> list[float]:
        """
        Convert per-token scores from a string of float scores 
        separated by ',' to a list of float numbers.
        """
        scores = scores.split(",")
        scores = list(map(float, scores))
        return scores

    def format_spectrum_id(self, spectrum_id: str) -> str:
        """
        TODO.
        Transform spectrum id generated by the algorithm to the common format
        `ms_run[i]:index=j` -> `filename:j`.
        """
        file_scan = spectrum_id
        spectrum_id = self.file_scan2spec_idx[file_scan]
        return spectrum_id

    def format_score(self, score: int) -> int:
        """
        NOTE: we have this method but don't use it for now!
        """
        score = score / self.SCORE_SCALE_CONST
        return score

    def format_scores(self, aa_scores):
        """
        TODO.
        """
        aa_scores = aa_scores.split(" ")
        aa_scores = list(map(lambda x: float(x) / self.SCORE_SCALE_CONST, aa_scores))
        aa_scores = self._format_scores(aa_scores)
        return aa_scores

    def format_sequence_and_scores(self, sequence, aa_scores):
        """
        Convert peptide sequence to the common output data format
        (ProForma with modifications represented with 
        Unimod accession codes, e.g. M[UNIMOD:35])
        and modify per-token scores if needed.

        This method is only needed if per-token scores have to be modified 
        to correspond the transformed sequence in ProForma format.
        Otherwise use `format_sequence` method instead.

        Parameters
        ----------
        sequence : str
            Peptide sequence in the original algorithm output format.
        aa_scores: str
            String of per-token scores for each token in the sequence.

        Returns
        -------
        transformed_sequence : str
            Peptide sequence in the common output data format.
        transformed_aa_scores: str
            String of per-token scores corresponding to each token
            in the transformed sequence.
        """   
        # direct (token-to-token) replacements
        for repl_args in self.REPLACEMENTS:
            sequence = sequence.replace(*repl_args)

        aa_scores = self.format_scores(aa_scores)
        return sequence, aa_scores


parser = argparse.ArgumentParser()
parser.add_argument(
    "--output_path", required=True, help="The path to the algorithm predictions file."
)
parser.add_argument(
    "--input_dir", required=True, help="The dir with the input dataset .mgf files.",
)
parser.add_argument(
    "--save_path", required=True, help="The path to save the processed predictions file."
)
args = parser.parse_args()

# Read predictions from output file
output_data = pd.read_csv(args.output_path)

# Rename columns to the expected column names if needed
output_data["spectrum_id"] = output_data["Source File"] + ":" + (output_data["Scan"]).astype(str)
output_data = output_data.rename(
    {
        "Peptide": "sequence",
        "Deep Novo Score (%)": "score",
        "local confidence (%)": "aa_scores",
    },
    axis=1,
)

# Transform data to the common output format
output_mapper = OutputMapper(input_dir=args.input_dir)
output_data = output_mapper.format_output(output_data[["spectrum_id", "sequence", "score", "aa_scores"]])

# Save processed predictions to outputs.csv
# (the expected name for the algorithm output file)
output_data.to_csv(args.save_path, index=False)
